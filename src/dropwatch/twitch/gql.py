"""Twitch GraphQL client.

Twitch's private GraphQL API only accepts *persisted* queries: you send a SHA-256
hash of a query document that Twitch's own web client ships, not the document
itself. Those hashes rotate whenever Twitch redeploys the player, which is the
single most likely way this bot breaks.

Two things follow from that, and they shape this whole module:

1. **Every hash lives in one registry** (:data:`OPERATIONS`) and every one of them
   is overridable from ``data/gql_operations.json`` without touching code, so a
   rotation is a config edit rather than a patch.
2. **A changed response shape is an error, never a zero.** Reading drop progress
   through a renamed field must not quietly return "0 minutes watched" — that
   would look exactly like a stream that isn't crediting. :func:`pluck` raises
   :class:`SchemaDriftError` instead, which phase 5 surfaces to Discord as
   "Twitch API changed, needs a fix".
"""

from __future__ import annotations

import asyncio
