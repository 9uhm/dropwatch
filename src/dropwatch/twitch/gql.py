#: Operations that read nothing account-specific and work without a token.
_ANONYMOUS = frozenset({"UseLive", "StreamMetadata", "DirectoryPage_Game"})

OPERATIONS: dict[str, Operation] = {
    name: Operation(
        name=name,
        sha256=_HASHES.get(name, ""),
        document=_DOCS.get(name),
        requires_auth=name not in _ANONYMOUS,
    )
    for name in _HASHES | _DOCS
}


def load_operation_overrides(path: Path | None = None) -> dict[str, str]:
    """Read ``{"OperationName": "sha256", ...}`` from ``data/gql_operations.json``.

    Exists so a hash rotation can be fixed by editing one JSON file — including
    from a phone, mid-event — rather than shipping a code change.
    """
    target = paths.DATA_DIR / "gql_operations.json" if path is None else path
    try:
        raw = json.loads(target.read_text("utf-8"))
    except FileNotFoundError:
        return {}
    except (OSError, json.JSONDecodeError) as exc:
        log.warning("ignoring unreadable gql_operations.json: %s", exc)
        return {}
    if not isinstance(raw, dict):
        log.warning("gql_operations.json must be an object of name -> hash")
        return {}
    return {str(k): str(v) for k, v in raw.items() if isinstance(v, str)}


def build_registry(overrides: dict[str, str] | None = None) -> dict[str, Operation]:
    ops = dict(OPERATIONS)
    for name, sha in (overrides or {}).items():
        if name in ops:
            if sha != ops[name].sha256:
                log.info("using overridden hash for %s", name)
            ops[name] = replace(ops[name], sha256=sha)
        else:
            log.warning("override for unknown operation %r ignored", name)
    return ops


# ----------------------------------------------------------------- field access


_MISSING = object()


def pluck(data: Any, *path: str | int, default: Any = _MISSING) -> Any:
    """Walk a nested response, raising :class:`SchemaDriftError` on a bad path.

    Pass ``default`` only where absence is genuinely meaningful — ``stream`` being
    ``None`` for an offline channel, say. Everywhere else, let it raise: a silent
    ``None`` from a renamed field is indistinguishable from "no progress", which
    is the exact failure this bot must never hide.
    """
    cursor = data
    for i, key in enumerate(path):
        try:
            cursor = cursor[key]
        except (KeyError, IndexError, TypeError):
            if default is not _MISSING:
                return default
            trail = " -> ".join(str(p) for p in path[: i + 1])
            raise SchemaDriftError(
                f"unexpected response shape at {trail!r} "
                f"(got {type(cursor).__name__})"
            ) from None
    return cursor


# ------------------------------------------------------------------------ client


class GQLClient:
    """Calls persisted GraphQL operations with retry, backoff and drift detection."""

    def __init__(
        self,
        session: aiohttp.ClientSession,
        auth: AuthManager,
        config: TwitchConfig,
        bus: EventBus,
        *,
        operations: dict[str, Operation] | None = None,
    ) -> None:
        self._session = session
        self._auth = auth
        self._config = config
        self._bus = bus
        self._ops = operations if operations is not None else build_registry(
            load_operation_overrides()
        )
        self._sem = asyncio.Semaphore(config.gql_max_concurrency)
        # Ops whose persisted hash Twitch rejected — don't keep paying for a
        # round trip we know will 400 before falling back.
        self._stale: set[str] = set()

    @property
    def operations(self) -> dict[str, Operation]:
        return dict(self._ops)

    @property
    def stale_operations(self) -> set[str]:
        return set(self._stale)

    async def call(
        self,
        operation: str,
        variables: dict[str, Any] | None = None,
        *,
        allow_document_fallback: bool = True,
    ) -> dict[str, Any]:
        """Run one operation and return its ``data`` object."""
        op = self._ops.get(operation)
        if op is None:
            raise GQLError(f"unknown operation {operation!r}")

        vars_ = variables or {}

        # Prefer the document we wrote and verified: persisted hashes rotate on
        # Twitch's schedule and are the known failure mode, whereas a document
        # only breaks if the schema itself changes — which breaks parsing anyway.
        # A hash is still used for operations we have no document for.
        use_document = bool(op.document) and (
            self._config.prefer_documents or operation in self._stale or not op.sha256
        )

        payload = op.document_payload(vars_) if use_document else op.persisted_payload(vars_)

        # _unwrap must be inside the try: a rejected hash is reported as a GraphQL
        # error in the response body, not as an HTTP status, so it surfaces from
        # _unwrap rather than _post. Wrapping only the POST leaves the fallback
        # below unreachable.
        try:
            body = await self._post(payload, op)
            return self._unwrap(body, op)
        except PersistedQueryNotFound:
            if not (allow_document_fallback and op.document and not use_document):
                self._stale.add(operation)
                await self._bus.publish(
                    EventType.SCHEMA_DRIFT,
                    operation=operation,
                    reason="persisted query hash rejected and no document fallback exists",
                )
                raise
            log.warning("%s hash is stale — retrying as a raw document", operation)
            self._stale.add(operation)
            body = await self._post(op.document_payload(vars_), op)
            return self._unwrap(body, op)

    async def _post(self, payload: Any, op: Operation) -> Any:
        headers: dict[str, str] = {"Client-ID": self._config.gql_client_id}
        if op.requires_auth or self._auth.authenticated:
            try:
                token = await self._auth.ensure_valid()
                headers["Authorization"] = f"OAuth {token}"
            except Exception:
                if op.requires_auth:
                    raise

        attempts = self._config.gql_max_retries + 1
        last: Exception | None = None

        for attempt in range(attempts):
            if attempt:
                await asyncio.sleep(self._backoff(attempt))
            async with self._sem:
                try:
                    async with self._session.post(
                        GQL_ENDPOINT, json=payload, headers=headers
                    ) as resp:
                        text = await resp.text()
                        if resp.status in RETRY_STATUSES:
                            last = GQLTransportError(
                                f"{op.name}: HTTP {resp.status}"
                            )
                            log.debug(
                                "%s got %s, retry %d/%d",
                                op.name, resp.status, attempt + 1, attempts,
                            )
                            continue
                        if resp.status == 401:
                            # One forced refresh, then let the next attempt use it.
                            if attempt == 0 and self._auth.authenticated:
                                log.info("%s got 401 — refreshing token", op.name)
                                await self._auth.refresh()
                                token = await self._auth.ensure_valid()
                                headers["Authorization"] = f"OAuth {token}"
                                last = GQLTransportError(f"{op.name}: HTTP 401")
                                continue
                            raise GQLTransportError(f"{op.name}: unauthorised")
                        if resp.status >= 400:
                            raise GQLTransportError(
                                f"{op.name}: HTTP {resp.status}: {text[:200]}"
                            )
                        try:
                            return json.loads(text)
                        except json.JSONDecodeError as exc:
                            raise SchemaDriftError(
                                f"{op.name}: response was not JSON: {text[:200]}"
                            ) from exc
                except (TimeoutError, aiohttp.ClientError) as exc:
                    last = GQLTransportError(f"{op.name}: {exc}")
                    log.debug(
                        "%s transport error, retry %d/%d: %s",
                        op.name, attempt + 1, attempts, exc,
                    )

        raise last or GQLTransportError(f"{op.name}: exhausted retries")

    def _backoff(self, attempt: int) -> float:
        """Exponential with full jitter, so concurrent callers don't resynchronise."""
        ceiling = min(
            self._config.gql_backoff_base * (2 ** (attempt - 1)),
            self._config.gql_backoff_max,
        )
        return random.uniform(0, ceiling)

    def _unwrap(self, body: Any, op: Operation) -> dict[str, Any]:
        # Twitch returns a bare object for one op and a list when batching.
        if isinstance(body, list):
            body = body[0] if body else {}
        if not isinstance(body, dict):
            raise SchemaDriftError(f"{op.name}: expected an object, got {type(body).__name__}")

        # Checked before `errors`: an integrity challenge also emits a generic
        # error, and reporting that instead would send someone chasing a schema
        # problem that doesn't exist.
        challenge = pluck(body, "extensions", "challenge", "type", default=None)
        if challenge == "integrity":
            raise IntegrityChallengeError(
                f"{op.name}: Twitch requires a Client-Integrity token for this "
                "operation, which this bot does not produce"
            )

        errors = body.get("errors")
        if errors:
            messages = [
                str(e.get("message", e)) if isinstance(e, dict) else str(e) for e in errors
            ]
            joined = "; ".join(messages)
            if any("PersistedQueryNotFound" in m for m in messages):
                raise PersistedQueryNotFound(f"{op.name}: {joined}")
            raise GQLError(f"{op.name}: {joined}")

        data = body.get("data")
        if data is None:
            raise SchemaDriftError(f"{op.name}: response contained no data")
        return data
