log = get_logger("twitch.gql")

GQL_ENDPOINT = "https://gql.twitch.tv/gql"

#: Retried transparently; anything else is surfaced.
RETRY_STATUSES = frozenset({429, 500, 502, 503, 504})


class GQLError(Exception):
    """Base for GraphQL failures."""


class GQLTransportError(GQLError):
    """Network or HTTP-level failure that outlived its retries."""


class SchemaDriftError(GQLError):
    """Twitch's response didn't match what we parse.

    Deliberately distinct from a transport error: this one needs a human to
    update an operation hash or a field path, and retrying will never help.
    """


class PersistedQueryNotFound(SchemaDriftError):
    """The operation hash is stale — Twitch has rotated its query documents."""


class IntegrityChallengeError(GQLError):
    """Twitch demanded a Client-Integrity token this bot cannot produce.

    The integrity header is generated by the real web player specifically to
    distinguish it from automation, and forging it is out of scope — so this is a
    permanent, honest "no" for the operation rather than something to retry.

    Callers should degrade to a manual path and say so plainly. Known to gate
    ``DropsPage_ClaimDropRewards`` and ``ViewerDropsDashboard``.
    """


@dataclass(frozen=True, slots=True)
class Operation:
    """A persisted GraphQL operation.

    ``document`` is an optional raw-query fallback. Twitch accepts raw documents
    for some operations and rejects them for others; when it works it lets the bot
    keep running through a hash rotation instead of going dark.
    """

    name: str
    sha256: str
    version: int = 1
    document: str | None = None
    requires_auth: bool = True

    def persisted_payload(self, variables: dict[str, Any]) -> dict[str, Any]:
        return {
            "operationName": self.name,
            "variables": variables,
            "extensions": {
                "persistedQuery": {"version": self.version, "sha256Hash": self.sha256}
            },
        }

    def document_payload(self, variables: dict[str, Any]) -> dict[str, Any]:
        if not self.document:
            raise SchemaDriftError(f"{self.name}: no raw-document fallback available")
        return {
            "operationName": self.name,
            "variables": variables,
            "query": self.document,
        }


